export type NativeRegister = "neutral" | "casual" | "polite";

export interface NativePhrase {
  id: string;
  english: string;
  ru: string;
  kk: string;
  example: string;
  note: string;
  register: NativeRegister;
}

export type NativeGroupId =
  "social" | "everyday" | "travel" | "work" | "wellbeing";

export interface NativeSituation {
  id: string;
  title: string;
  description: string;
  group: NativeGroupId;
  icon: string;
  phrases: NativePhrase[];
}

export const nativeGroups: { id: NativeGroupId; label: string }[] = [
  { id: "social", label: "Общение" },
  { id: "everyday", label: "Каждый день" },
  { id: "travel", label: "В дороге" },
  { id: "work", label: "Работа и учёба" },
  { id: "wellbeing", label: "Забота о себе" },
];

type PhraseRow = [
  english: string,
  ru: string,
  kk: string,
  example: string,
  note: string,
  register: NativeRegister,
];

function situation(
  id: string,
  title: string,
  description: string,
  group: NativeGroupId,
  icon: string,
  rows: PhraseRow[],
): NativeSituation {
  return {
    id,
    title,
    description,
    group,
    icon,
    phrases: rows.map(([english, ru, kk, example, note, register], index) => ({
      id: `${id}-${index + 1}`,
      english,
      ru,
      kk,
      example,
      note,
      register,
    })),
  };
}

