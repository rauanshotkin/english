export function normalizeWord(word: string): string {
  return word
    .toLowerCase()
    .replace(/[‘’]/g, "'")
    .replace(/^[^a-z]+|[^a-z]+$/g, "")
    .replace(/'s$/, "");
}

export function lookupTranslation(
  word: string,
  target: TranslationTarget = "kk",
): string | undefined {
  const key = normalizeWord(word);
  const selectedDictionary = target === "ru" ? dictionary : dictionaryKK;
  return selectedDictionary[key];
}
